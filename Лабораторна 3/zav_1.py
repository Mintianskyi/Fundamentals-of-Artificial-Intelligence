from llm_helper import ask_llm, save_report


def run():
    output = ["Завдання 1: 5 типів запитів (Предметна область: Програмування)\n"]

    tasks = [
        (
            "1. Пояснення",
            "Поясни простими словами, що таке рекурсія в програмуванні, і наведи короткий приклад на Python.",
        ),
        (
            "2. Генерація тексту",
            "Напиши короткий текст (3-4 речення) про важливість алгоритмів та структур даних для розробника.",
        ),
        (
            "3. Переклад",
            "Переклади англійською: 'Об'єктно-орієнтоване програмування базується на інкапсуляції, наслідуванні та поліморфізмі.'",
        ),
        (
            "4. Узагальнення",
            "Узагальни одним реченням: 'База даних — це організована сукупність даних. Управління ними здійснюється через СУБД за допомогою мови запитів SQL для створення, зміни та пошуку інформації.'",
        ),
        (
            "5. Генерація списку",
            "Сформуй нумерований список із 3 популярних фреймворків Python для веб-розробки з коротким описом кожного.",
        ),
    ]

    for title, prompt in tasks:
        block = f"--- {title} ---\nPrompt: {prompt}\nВідповідь:\n{ask_llm(prompt)}\n"
        print(block)
        output.append(block)

    save_report("result_task1.txt", output)


if __name__ == "__main__":
    run()